#!/usr/bin/env bash
# Create the ignored root .env with fresh secrets. Never overwrites an existing
# .env and never prints a secret value.
#
# Usage: scripts/bootstrap-env.sh
# Optional environment overrides:
#   APP_PORT, PUBLIC_ORIGIN, OWNER_USERNAME, POSTGRES_DB, POSTGRES_USER,
#   APP_DB_USER, OWNER_PASSWORD_HASH

# If OWNER_PASSWORD_HASH is unset, the script prompts for the owner password
# (hidden, twice) and hashes it with the API image's `python -m app.password_hash`.
set -Eeuo pipefail
umask 077

ROOT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
ENV_FILE="$ROOT_DIR/.env"

die() {
    printf 'error: %s\n' "$*" >&2
    exit 1
}

command -v openssl >/dev/null 2>&1 || die "openssl is required"
[[ ! -e "$ENV_FILE" && ! -L "$ENV_FILE" ]] || die ".env already exists; move it aside before bootstrapping again"

app_port="${APP_PORT:-8080}"
public_origin="${PUBLIC_ORIGIN:-http://127.0.0.1:$app_port}"
owner_username="${OWNER_USERNAME:-owner}"
postgres_db="${POSTGRES_DB:-agent_office}"
app_db_user="${APP_DB_USER:-agent_office_app}"
postgres_user="${POSTGRES_USER:-agent_office_admin}"
runner_uid="${RUNNER_UID:-$(id -u)}"
runner_gid="${RUNNER_GID:-$(id -g)}"

[[ "$app_port" =~ ^[0-9]{1,5}$ ]] || die "APP_PORT must be a TCP port number"
(( 10#$app_port >= 1 && 10#$app_port <= 65535 )) || die "APP_PORT must be between 1 and 65535"
[[ "$public_origin" =~ ^https?://[^[:space:]/]+$ ]] \
    || die "PUBLIC_ORIGIN must be an exact http(s) origin without a path or trailing slash"
[[ "$owner_username" =~ ^[A-Za-z0-9._-]{1,64}$ ]] || die "OWNER_USERNAME contains unsupported characters"
[[ "$postgres_db" =~ ^[a-z][a-z0-9_]{0,62}$ ]] || die "POSTGRES_DB must be a lowercase SQL identifier"
[[ "$app_db_user" =~ ^[a-z][a-z0-9_]{0,62}$ ]] || die "APP_DB_USER must be a lowercase SQL identifier"
[[ "$app_db_user" != "$postgres_user" ]] || die "APP_DB_USER must differ from the PostgreSQL admin user"
[[ "$postgres_user" =~ ^[a-z][a-z0-9_]{0,62}$ ]] || die "POSTGRES_USER must be a lowercase SQL identifier"
[[ "$runner_uid" =~ ^[1-9][0-9]{0,9}$ ]] || die "RUNNER_UID must be a non-root numeric user id"
[[ "$runner_gid" =~ ^[1-9][0-9]{0,9}$ ]] || die "RUNNER_GID must be a non-root numeric group id"

case "$public_origin" in
    https://*)
        app_env="${APP_ENV:-production}"
        cookie_secure="true"
        ;;
    http://*)
        app_env="${APP_ENV:-development}"
        cookie_secure="false"
        ;;
esac
[[ "$app_env" == "development" || "$app_env" == "production" ]] \
    || die "APP_ENV must be development or production"
[ "$app_env" != "production" ] || [ "$cookie_secure" = "true" ] \
    || die "production requires an https PUBLIC_ORIGIN"

owner_hash="${OWNER_PASSWORD_HASH:-}"
if [ -z "$owner_hash" ]; then
    [ -t 0 ] || die "OWNER_PASSWORD_HASH is unset and stdin is not a terminal"
    printf 'Owner password (hidden, min 12 chars): ' >&2
    IFS= read -r -s owner_password
    printf '\n' >&2
    printf 'Repeat owner password: ' >&2
    IFS= read -r -s owner_password_confirm
    printf '\n' >&2
    [ "$owner_password" = "$owner_password_confirm" ] || die "owner passwords do not match"
    [ "${#owner_password}" -ge 12 ] || die "owner password must be at least 12 characters"

    command -v docker >/dev/null 2>&1 || die "docker is required to hash the owner password"
    image="agent-office-bootstrap-api:bootstrap-$$"
    trap 'docker image rm "$image" >/dev/null 2>&1 || true' EXIT
    printf 'Building API image to hash the owner password (no secret is sent as an argument)...\n' >&2
    docker build --quiet --tag "$image" "$ROOT_DIR/apps/api" >/dev/null \
        || die "API image build failed"
    owner_hash="$(printf '%s\n' "$owner_password" | docker run --rm -i --entrypoint python "$image" -m app.password_hash)"
    unset owner_password owner_password_confirm
    docker image rm "$image" >/dev/null 2>&1 || die "could not remove temporary password-hasher image"
    trap - EXIT
fi

argon2id_re='^\$argon2id\$[A-Za-z0-9./+,=$-]{20,}$'
[[ "$owner_hash" =~ $argon2id_re ]] \
    || die "OWNER_PASSWORD_HASH must be an Argon2id hash produced by the API"

postgres_password="$(openssl rand -hex 32)"
app_db_password="$(openssl rand -hex 32)"
runner_shared_token="$(openssl rand -hex 32)"
runtime_launcher_token="$(openssl rand -hex 32)"
tmp="$(mktemp "$ROOT_DIR/.env.XXXXXX")"
trap 'rm -f "$tmp"' EXIT

{
    printf '# Generated by scripts/bootstrap-env.sh. Never commit this file.\n'
    printf 'APP_ENV=%s\n' "$app_env"
    printf 'APP_PORT=%s\n' "$app_port"
    printf 'PUBLIC_ORIGIN=%s\n' "$public_origin"
    printf 'POSTGRES_DB=%s\n' "$postgres_db"
    printf 'POSTGRES_USER=%s\n' "$postgres_user"
    printf 'POSTGRES_PASSWORD=%s\n' "$postgres_password"
    printf 'APP_DB_USER=%s\n' "$app_db_user"
    printf 'APP_DB_PASSWORD=%s\n' "$app_db_password"
    printf 'DATABASE_URL=postgresql+asyncpg://%s:%s@db:5432/%s\n' \
        "$app_db_user" "$app_db_password" "$postgres_db"
    printf 'MIGRATION_DATABASE_URL=postgresql+asyncpg://%s:%s@db:5432/%s\n' \
        "$postgres_user" "$postgres_password" "$postgres_db"
    printf 'OWNER_USERNAME=%s\n' "$owner_username"
    # Single quotes keep Compose from expanding the hash's leading '$'.
    printf "OWNER_PASSWORD_HASH='%s'\n" "$owner_hash"
    printf 'SESSION_SECRET=%s\n' "$session_secret"
    printf 'RUNNER_SHARED_TOKEN=%s\n' "$runner_shared_token"
    printf 'RUNTIME_LAUNCHER_TOKEN=%s\n' "$runtime_launcher_token"
    printf 'RUNNER_UID=%s\n' "$runner_uid"
    printf 'RUNNER_GID=%s\n' "$runner_gid"
    printf 'SESSION_TTL_SECONDS=28800\n'
    printf 'SESSION_COOKIE_SECURE=%s\n' "$cookie_secure"
    printf 'SESSION_COOKIE_SAMESITE=strict\n'
    printf 'LOG_LEVEL=INFO\n'
} >"$tmp"

chmod 600 "$tmp"
ln -- "$tmp" "$ENV_FILE" || die ".env was created while bootstrapping; refusing to replace it"
rm -f -- "$tmp"
trap - EXIT

printf 'wrote %s (mode 600, ignored by git)\n' "$ENV_FILE"
printf 'no secret values were printed\n'
printf 'next: docker compose build && docker compose up -d\n'
